/**
 * Generate the CloudFront viewer-request function from the build output.
 *
 * Two jobs, and the second is why this is generated rather than hand-written.
 *
 * 1. Directory-style requests. `trailingSlash: true` writes /jobs/index.html,
 *    and DefaultRootObject only applies at the root, so /jobs/ asks S3 for a
 *    key that is not there.
 *
 * 2. Pages published since the last build. A static export has a file per
 *    known slug, so a doc page or role added in the admin panel afterwards has
 *    none and answers 404 - while still appearing in the navigation, which is
 *    read live. A dead link in a live menu is the worst of both. So a path
 *    under a dynamic route is sent to that route's pre-rendered shell, which
 *    reads the slug from the URL and fetches the content. Publishing then
 *    works with no rebuild.
 *
 * The root is the awkward one: /<slug>/ is a real route for CMS pages, but
 * /login/ and /dashboard/ are not. Guessing that list in a hand-written
 * function is how it silently goes wrong six months later, so it is read from
 * `out/` at deploy time and cannot drift from what was actually built.
 *
 * The output of this belongs to the website's distribution ONLY, published as
 * `aravo-web-routes`. The admin and CMS panels are separate distributions with
 * their own `aravo-dir-index`, which does the directory rewrite and nothing
 * else. Publishing this one over theirs breaks every route they have, because
 * the reserved list below is this site's and knows nothing about /companies/
 * or /jobs/, so those get sent to a shell that does not exist there.
 */

import { readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve(process.argv[2] ?? "out");
const DEST = resolve(process.argv[3] ?? "scripts/cf-dir-index.js");

// Every top-level name the build produced. A request whose first segment is
// one of these is a real route or a real asset, and must be left alone.
const reserved = readdirSync(OUT, { withFileTypes: true })
  .map((e) => e.name)
  .filter((name) => !name.startsWith("."))
  // Strip the extension so "404.html" reserves "404" as well, which is what
  // the /404 route resolves to.
  .map((name) => name.replace(/\.[^.]+$/, ""))
  .sort();

const source = `// GENERATED by scripts/build-cf-function.mjs - do not edit here.
//
// Regenerated on every deploy from the contents of out/, so the reserved list
// below is always what was actually built rather than what somebody remembered
// to add.

// Top-level names that are real routes or assets. Anything else at the root is
// treated as a CMS page and sent to the shell.
var RESERVED = ${JSON.stringify(reserved)};

// Dynamic routes, and the shell pre-rendered for each. A path directly under
// one of these prefixes is served its shell, which reads the slug from the URL.
// The prefix index itself (/docs/) is a real page and is left alone.
var DYNAMIC = ['/docs/', '/careers/'];

var SHELL = '_shell';

// Next asks for a route's React payload as a sibling file when navigating
// between pages, e.g. /docs/<slug>/__next.docs.$d$slug.__PAGE__.txt. A slug
// published since the last build has no such file, which is a 404 in the
// console of an otherwise working page. The shell's copy is byte-identical in
// name and purpose, so it answers for every slug.
var PAYLOAD_PREFIX = '__next.';

function handler(event) {
    var request = event.request;
    var uri = request.uri;

    // Trailing slashes, without a regex: inside the template literal that
    // generates this file, an escaped slash collapses and silently produces a
    // comment instead of a pattern.
    var trimmed = uri;
    while (trimmed.length > 1 && trimmed.charAt(trimmed.length - 1) === '/') {
        trimmed = trimmed.substring(0, trimmed.length - 1);
    }
    if (trimmed === '/') { trimmed = ''; }
    var segments = trimmed.split('/').filter(function (s) { return s.length > 0; });

    // The root itself.
    if (segments.length === 0) {
        request.uri = '/index.html';
        return request;
    }

    var last = segments[segments.length - 1];

    // A React payload belonging to a dynamic route. Checked before the
    // extension test below, which would otherwise pass it straight through.
    if (last.indexOf(PAYLOAD_PREFIX) === 0 && segments.length >= 2) {
        for (var p = 0; p < DYNAMIC.length; p++) {
            if (uri.indexOf(DYNAMIC[p]) === 0 && segments.length === 3) {
                request.uri = DYNAMIC[p] + SHELL + '/' + last;
                return request;
            }
        }
        if (segments.length === 2 && RESERVED.indexOf(segments[0]) === -1) {
            request.uri = '/' + SHELL + '/' + last;
            return request;
        }
        return request;
    }

    // Anything else with an extension is an asset and keeps its own path.
    if (last.indexOf('.') !== -1) {
        return request;
    }

    // One level under a dynamic prefix, e.g. /docs/offline-and-recovery.
    for (var i = 0; i < DYNAMIC.length; i++) {
        if (uri.indexOf(DYNAMIC[i]) === 0 && segments.length === 2) {
            request.uri = DYNAMIC[i] + SHELL + '/index.html';
            return request;
        }
    }

    // A single unreserved segment at the root is a CMS page: /refund-policy.
    if (segments.length === 1 && RESERVED.indexOf(segments[0]) === -1) {
        request.uri = '/' + SHELL + '/index.html';
        return request;
    }

    request.uri = trimmed + '/index.html';
    return request;
}
`;

writeFileSync(DEST, source);
console.log(`  wrote ${DEST}`);
console.log(`  reserved (${reserved.length}): ${reserved.join(" ")}`);
